package OperatorsAndDecisionMaking;

public class PositiveNegativeOrZero {
    static void main() {
        int num = 1;
        if (num > 0){
            System.out.println("Positive number");
        } else if (num < 0) {
            System.out.println("Negative number");
        } else {
            System.out.println("Zero");
        }
    }
}
